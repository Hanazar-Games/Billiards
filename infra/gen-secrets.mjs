// Prints the secrets of a production infra/.env (F4-13, D065), each 24 random
// bytes in hex. Usage: node infra/gen-secrets.mjs >> infra/.env (after the
// NAKAMA_DOMAIN and ACME_EMAIL lines; docs/f4/implantacao.md).
import { randomBytes } from 'node:crypto';
import { SECRET_KEYS } from './check-env.mjs';

console.log(`# Secrets generated by infra/gen-secrets.mjs on ${new Date().toISOString().slice(0, 10)}`);
for (const key of SECRET_KEYS) console.log(`${key}=${randomBytes(24).toString('hex')}`);
